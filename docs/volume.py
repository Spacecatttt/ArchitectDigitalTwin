"""Розрахунок обсягу телеметрії за формулою (1): V = T · Σ s_i · f_i.

Об'єкт: вертикально-фрезерний обробний центр із ЧПК (варіант 3).
Запуск: python3 docs/volume.py
"""

# (ідентифікатор, назва, розмір відліку s_i, байт, частота опитування f_i, Гц)
SIGNALS = [
    ("S01", "Вібрація шпинделя (сирий сигнал)",      2, 5000.0),
    ("S02", "Навантаження шпинделя",                  4,   25.0),
    ("S03", "Фактичні оберти шпинделя",               4,    5.0),
    ("S04", "Положення осі X",                        8,   10.0),
    ("S05", "Положення осі Y",                        8,   10.0),
    ("S06", "Положення осі Z",                        8,   10.0),
    ("S07", "Фактична подача",                        4,    5.0),
    ("S08", "Струм приводу осі X",                    4,   25.0),
    ("S09", "Температура підшипників шпинделя",       4,    0.1),
    ("S10", "Температура МОР",                        4,    0.1),
    ("S11", "Режим роботи ЧПК",                       1,    1.0),
    ("S12", "Номер активного інструмента",            1,    1.0),
    ("S13", "Код активної аварії",                    2,    1.0),
]

T_DAY = 86_400                      # с, тривалість спостереження (доба)
FEATURES = 8                        # ознак вібрації, що обчислює шлюз (ADR-0003)
FEATURE_SIZE, FEATURE_RATE = 4, 10  # байт, Гц
CUT_HOURS = 2 * 8 * 0.6             # дві зміни по 8 год, частка різання 60 %
RAW_RETENTION_DAYS = 7              # ковзне вікно сирої вібрації (ADR-0001)


def rate(signals):
    """Сумарний потік, байт/с: Σ s_i · f_i."""
    return sum(s * f for _, _, s, f in signals)


def main():
    print(f"{'Id':<4} {'Сигнал':<36} {'s, Б':>5} {'f, Гц':>8} {'s·f, Б/с':>10}")
    for sid, name, s, f in SIGNALS:
        print(f"{sid:<4} {name:<36} {s:>5} {f:>8g} {s * f:>10.1f}")
    total = rate(SIGNALS)
    v_day = total * T_DAY
    vib = SIGNALS[0][2] * SIGNALS[0][3]
    print(f"\nΣ s_i·f_i = {total:.1f} Б/с")
    print(f"V(доба) = {T_DAY} · {total:.1f} = {v_day:,.0f} Б "
          f"≈ {v_day / 1e6:.1f} МБ ≈ {v_day / 2**20:.1f} МіБ")
    print(f"Частка сирої вібрації S01: {vib / total:.1%}")

    # Обсяг після рішень ADR-0001 / ADR-0003
    slow = total - vib
    feat = FEATURES * FEATURE_SIZE * FEATURE_RATE
    hot_rate = slow + feat
    hot_day = hot_rate * T_DAY
    raw_day = vib * CUT_HOURS * 3600
    print("\nПісля обчислення ознак на шлюзі (ADR-0003):")
    print(f"  повільні сигнали S02–S13: {slow:.1f} Б/с; ознаки вібрації: {feat} Б/с")
    print(f"  потік до платформи: {hot_rate:.1f} Б/с "
          f"(зменшення на {1 - hot_rate / total:.1%})")
    print(f"  сховище часових рядів: {hot_day / 1e6:.1f} МБ/добу, "
          f"{hot_day * 365 / 1e9:.1f} ГБ/рік без стиснення")
    print(f"  сира вібрація лише під час різання: {raw_day / 1e6:.1f} МБ/добу, "
          f"вікно {RAW_RETENTION_DAYS} діб = {raw_day * RAW_RETENTION_DAYS / 1e9:.2f} ГБ")
    rows_year = hot_rate / 4 * T_DAY * 365  # грубо: ~4 Б корисних даних на рядок
    print(f"  ≈ {rows_year / 1e9:.1f} млрд значень на рік")


if __name__ == "__main__":
    main()
